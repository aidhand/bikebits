export function slugify(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^\w\s-]/g, "")
    .trim()
    .replace(/[\s_]+/g, "-")
    .replace(/-+/g, "-");
}

export function normalizeAttr(s: string): string {
  return s.toLowerCase().trim().replace(/\s+/g, " ");
}
